/**
 * Generated by ValleyVis from "Up (from UpRoutine)".
 * Poses are written in the blue frame; field() mirrors them for red.
 */
public abstract class TestSoloRoutine extends AutoBase {
    @Override
    public Pose startingPose() {
        return field().of(72.0 + Constants.ROBOT_LENGTH / 2.0, 144.0 - Constants.ROBOT_WIDTH / 2.0, -90.0);
    }

    @Override
    protected Command routine() {
        PoseFactory f = field();

        /* ----- Poses ----- */
        Pose start = startingPose();
        Pose gardenAlign = f.of(114.5, 135.5, 0.0);
        Pose gardenIn = f.of(135.5, 135.5, 0.0);
        Pose cellAlign = f.of(84.0, 111.5, -150.0);
        Pose shoot2 = f.of(107.5, 14.0, 120.0);
        Pose moveToShootJoint1 = f.of(82.0, 48.0, 0.0);

        /* ----- Paths ----- */
        Path alignForGarden = Paths.curve(start, f.of(86.5, 128.5, 0.0), gardenAlign)
                .linear(start, gardenAlign);
        Path gardenIntake = Paths.line(gardenAlign, gardenIn)
                .linear(gardenAlign, gardenIn);
        Path intakeFromTip = Paths.line(gardenIn, cellAlign)
                .linear(gardenIn, cellAlign, 0.4);
        Path moveToShoot = Paths.path(
                        Paths.line(cellAlign, moveToShootJoint1),
                        Paths.line(moveToShootJoint1, shoot2))
                .linear(cellAlign, shoot2);

        return PedroAutoDsl.auto(subsystems.drive, b -> {
            // Shoot preloaded
            b.command(new ShootCmd(subsystems.intake, subsystems.pollen, subsystems.transfer, 4000));
            b.follow(alignForGarden);
            b.command(subsystems.drive.follow(gardenIntake)
                    .deadlineWith(
                            CommandFactory.intakeAndTransfer(subsystems.intake, subsystems.transfer))
                    .withTimeout(2));
            // Intake From Garden
            b.command(CommandFactory.intakeAndTransfer(subsystems.intake, subsystems.transfer).withTimeout(2.0));
            b.command(subsystems.drive.follow(intakeFromTip)
                    .deadlineWith(
                            CommandFactory.intakeAndTransfer(subsystems.intake, subsystems.transfer)));
            b.command(subsystems.drive.follow(moveToShoot)
                    .deadlineWith(
                            Commands.sequence(
                                    Commands.waitUntil(() -> reached(1, 37.11)),
                                    Commands.runOnce(() -> { subsystems.pollen.shoot(); }))));
            // shoot2
            b.command(new ShootCmd(subsystems.intake, subsystems.pollen, subsystems.transfer, 4000));
        });
    }

    /**
     * True once the follower is on path segment {@code segment} with at most {@code inchesLeft}
     * to go in it, or is already past that segment. Uses remainingDistance() because in
     * Pedro 3.0.1 completion() mixes the segment t with the whole path on multi-segment paths.
     */
    private boolean reached(int segment, double inchesLeft) {
        Follower follower = subsystems.drive.getFollower();
        return follower.pathIndex() > segment
                || (follower.pathIndex() == segment && follower.remainingDistance() <= inchesLeft);
    }
}
